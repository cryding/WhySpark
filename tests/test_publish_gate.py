import unittest

from src.publish_gate import (
    evaluate_publish_gate,
    validate_metadata,
    validate_research,
    validate_rights,
    validate_render,
)


class GateTests(unittest.TestCase):
    def test_missing_research_fails_closed(self):
        self.assertTrue(validate_research({}, 2))

    def test_one_source_cannot_pass(self):
        research = {
            "sources": [{
                "id": "a", "url": "https://www.nasa.gov/story",
                "title": "Science report", "published_at": "2026-10-13",
                "evidence_text": "The science report provides evidence about a planet."
            }],
            "claims": [{
                "text": "The science report provides evidence about a planet",
                "evidence_source_ids": ["a"]
            }]
        }
        self.assertTrue(validate_research(research, 2))

    def test_missing_rights_inventory_fails(self):
        self.assertTrue(validate_rights({}))

    def test_bad_metadata_fails(self):
        self.assertTrue(validate_metadata({"title": "", "description": "", "tags": [], "category_id": "x"}))

    def test_missing_render_fails(self):
        self.assertTrue(validate_render({}))

    def test_gate_blocks_if_any_subsystem_fails(self):
        result = evaluate_publish_gate({}, {}, {}, {})
        self.assertFalse(result["passed"])
        self.assertEqual(result["decision"], "BLOCK")
        self.assertTrue(result["errors"])

    def test_valid_original_asset_rights_record(self):
        rights = {"assets": [{
            "origin": "generated by WhySpark renderer",
            "rights_status": "original_project_generated",
            "creator": "WhySpark local renderer",
            "license": "project-original",
            "third_party_media": False
        }]}
        self.assertEqual(validate_rights(rights), [])


if __name__ == "__main__":
    unittest.main()
